import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision import models

# Squeeze-and-Excitation (SE) Block
class SEBlock(nn.Module):
    def __init__(self, in_channels, reduction=16):
        super(SEBlock, self).__init__()
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.fc = nn.Sequential(
            nn.Linear(in_channels, in_channels // reduction),
            nn.SiLU(inplace=True),
            nn.Linear(in_channels // reduction, in_channels),
            nn.Sigmoid()
        )

    def forward(self, x):
        b, c, _, _ = x.size()
        y = self.pool(x).view(b, c)
        y = self.fc(y).view(b, c, 1, 1)
        return x * y

# Hybrid CNN Model with ResNet34 base
class HybridCNN(nn.Module):
    def __init__(self, num_classes, fine_tune_resnet=False):
        super(HybridCNN, self).__init__()

        # Load pretrained ResNet34
        resnet34 = models.resnet34(pretrained=True)

        # Keep layers up to layer3
        self.resnet_base = nn.Sequential(
            resnet34.conv1,
            resnet34.bn1,
            resnet34.relu,
            resnet34.maxpool,
            resnet34.layer1,
            resnet34.layer2,
            resnet34.layer3
        )

        # Optionally fine-tune some ResNet layers
        for param in self.resnet_base.parameters():
            param.requires_grad = fine_tune_resnet

        # Custom conv layers with SE and SiLU
        self.custom_conv = nn.Sequential(
            nn.Conv2d(256, 256, kernel_size=3, padding=1),
            nn.BatchNorm2d(256),
            nn.SiLU(),
            SEBlock(256),
            nn.MaxPool2d(2),

            nn.Conv2d(256, 512, kernel_size=3, padding=1),
            nn.BatchNorm2d(512),
            nn.SiLU(),
            SEBlock(512),
            nn.AdaptiveAvgPool2d((1, 1))
        )

        # Classifier
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(512, 256),
            nn.SiLU(),
            nn.Dropout(0.5),
            nn.Linear(256, num_classes)
        )

        # Initialize custom layers
        self.custom_conv.apply(self._init_weights)
        self.classifier.apply(self._init_weights)

    def _init_weights(self, m):
        if isinstance(m, nn.Conv2d) or isinstance(m, nn.Linear):
            nn.init.kaiming_normal_(m.weight, mode='fan_out', nonlinearity='relu')
            if m.bias is not None:
                nn.init.constant_(m.bias, 0)

    def forward(self, x):
        x = self.resnet_base(x)
        x = self.custom_conv(x)
        x = self.classifier(x)
        return x

