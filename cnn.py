# Training loop for custom model
for epoch in range(num_epochs):
    print(f"Epoch {epoch+1}/{num_epochs}")

    running_loss = 0.0  # Accumulate loss for the epoch

    for batch_idx, (data, targets) in enumerate(train_loader):
        data = data.to(device)
        targets = targets.to(device)

        # Forward
        scores = model(data)
        loss = criterion(scores, targets)

        # Backward
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        running_loss += loss.item()

    epoch_loss = running_loss / len(train_loader)  # Calculate average epoch loss
    epoch_losses.append(epoch_loss)
    epochs.append(epoch + 1)  # Store epoch number
    print(f"Training Loss: {epoch_loss:.4f}")  # Print training loss

    scheduler.step()

    # Calculate validation loss for custom model
    model.eval()  # Set to evaluation mode
    with torch.no_grad():
        val_loss = 0.0
        for batch_idx, (data, targets) in enumerate(val_loader):
            data = data.to(device)
            targets = targets.to(device)
            outputs = model(data)
            loss = criterion(outputs, targets)
            val_loss += loss.item()
    val_losses.append(val_loss / len(val_loader))
    print(f"Validation Loss: {val_loss / len(val_loader):.4f}")  # Print validation loss
    model.train()  # Set back to training mode

