import random
import numpy as np

def show_random_images(dataset, class_names, num_images=5):
    fig, axes = plt.subplots(1, num_images, figsize=(15, 5))

    for i in range(num_images):
        idx = random.randint(0, len(dataset) - 1)  # Select a random index
        img, label = dataset[idx]  # Get image and label

        # Unnormalize the image
        mean = np.array([0.485, 0.456, 0.406]) #your mean used in transform
        std = np.array([0.229, 0.224, 0.225])  #your std used in transform
        img = img.numpy() #convert tensor to numpy array
        img = std[:, None, None] * img + mean[:, None, None] #apply the unnormalization formula
        img = np.clip(img, 0, 1) #clip any values still outside the valid range.
        img = img.transpose((1, 2, 0))  # Convert to (H, W, C) format for displaying

        axes[i].imshow(img)  # Unnormalized image
        axes[i].set_title(class_names[label])  # Set title as class name
        axes[i].axis("off")  # Hide axes

    plt.show()

# Call function
